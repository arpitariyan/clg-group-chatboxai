export function getAllApps() {
  return APP_REGISTRY;
}

export function getAppById(id) {
  return APP_REGISTRY.find(app => app.id === id) || null;
}

export function getAppsByCategory(category) {
  return APP_REGISTRY.filter(app => app.category === category);
}

export function getToolSchema(appId, toolId) {
  const app = getAppById(appId);
  if (!app) return null;
  return app.tools.find(t => t.id === toolId) || null;
}

export function getOAuthApps() {
  return APP_REGISTRY.filter(app => app.connectionType === 'oauth' && app.oauth?.authUrl);
}

export function getLocalApps() {
  return APP_REGISTRY.filter(app => app.connectionType === 'local');
}

/**
 * Serialize tool definitions for LLM system prompt (function-calling format)
 */
export function serializeToolsForLLM(connectedApps) {
  const tools = [];
  for (const connection of connectedApps) {
    const app = getAppById(connection.appId);
    if (!app) continue;
    for (const tool of app.tools) {
      tools.push({
        type: 'function',
        function: {
          name: tool.id,
          description: `[${app.name}] ${tool.description}`,
          parameters: {
            type: 'object',
            properties: Object.fromEntries(
              Object.entries(tool.parameters).map(([key, def]) => [
                key,
                { type: def.type === 'array' ? 'array' : def.type === 'date' ? 'string' : def.type, description: def.description },
              ])
            ),
            required: Object.entries(tool.parameters)
              .filter(([, def]) => def.required)
              .map(([key]) => key),
          },
        },
      });
    }
  }
  return tools;
}

