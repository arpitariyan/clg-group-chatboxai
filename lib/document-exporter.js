export function downloadAsMarkdown(title = 'Document', content = '') {
  if (typeof window === 'undefined') return;

  const sanitizedTitle = String(title || 'Document').replace(/[^\w\s-]/g, '').trim() || 'Report';
  const fileName = `${sanitizedTitle.toLowerCase().replace(/\s+/g, '_')}.md`;
  const markdownText = `# ${title}\n\n${content}`;

  downloadBlob(markdownText, fileName, 'text/markdown;charset=utf-8');
}

function downloadBlob(content, fileName, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }, 100);
}

function escapeHTML(str) {
  return String(str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

function formatMarkdownToHTML(markdown = '') {
  if (!markdown) return '';

  let html = String(markdown);

  // Headers
  html = html.replace(/^### (.*$)/gim, '<h3>$1</h3>');
  html = html.replace(/^## (.*$)/gim, '<h2>$1</h2>');
  html = html.replace(/^# (.*$)/gim, '<h1>$1</h1>');

  // Bold & Italic
  html = html.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
  html = html.replace(/\*(.*?)\*/g, '<em>$1</em>');

  // Simple Markdown Tables to HTML Tables
  const lines = html.split('\n');
  let inTable = false;
  let tableHtml = '';
  const resultLines = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (line.startsWith('|') && line.endsWith('|')) {
      if (line.includes('---')) continue; // Skip separator line
      const cells = line.split('|').slice(1, -1).map(c => c.trim());
      if (!inTable) {
        inTable = true;
        tableHtml = '<table><thead><tr>' + cells.map(c => `<th>${c}</th>`).join('') + '</tr></thead><tbody>';
      } else {
        tableHtml += '<tr>' + cells.map(c => `<td>${c}</td>`).join('') + '</tr>';
      }
    } else {
      if (inTable) {
        tableHtml += '</tbody></table>';
        resultLines.push(tableHtml);
        inTable = false;
        tableHtml = '';
      }
      if (line) {
        if (!line.startsWith('<h') && !line.startsWith('<ul') && !line.startsWith('<ol')) {
          resultLines.push(`<p>${line}</p>`);
        } else {
          resultLines.push(line);
        }
      }
    }
  }

  if (inTable) {
    tableHtml += '</tbody></table>';
    resultLines.push(tableHtml);
  }

  return resultLines.join('\n');
}
